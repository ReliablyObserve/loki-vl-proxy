STATUS_CONST = {"StatusClientClosedRequest": 499}
SHAPE_NAMES = {"ShapeRoute": "route", "ShapeFrontend": "frontend", "ShapeHTTPError": "http_error", "ShapeBodyless": "bodyless",
               "ShapeFormatQuery": "format_query", "ShapeRulerJSON": "ruler_json", "ShapeAlertsJSON": "alerts_json"}


def load_rows(path):
    """(header text, rows with their line text) of a recorded-answers file."""
    lines = [line for line in read_text(path).split("\n") if line.strip()]
    head = json.loads(lines[0])["_source"]
    return head, [json.loads(line) for line in lines[1:]]


def go_string(literal):
    return json.loads(literal)


def split_top_level(expr, sep):
    parts, depth, quote, current = [], 0, None, []
    i = 0
    while i < len(expr):
        c = expr[i]
        if quote:
            current.append(c)
            if c == "\\" and quote != "`":
                current.append(expr[i + 1])
                i += 1
            elif c == quote:
                quote = None
        elif c in "\"`":
            quote = c
            current.append(c)
        elif c in "([{":
            depth += 1
            current.append(c)
        elif c in ")]}":
            depth -= 1
            current.append(c)
        elif c == sep and depth == 0:
            parts.append("".join(current).strip())
            current = []
        else:
            current.append(c)
        i += 1
    parts.append("".join(current).strip())
    return parts


def template_of(expr, texts):
    """The text a Go constructor expression renders, variable parts as <name>; None when it is no plain concatenation."""
    out = []
    for part in split_top_level(expr, "+"):
        if re.fullmatch(r'"(?:[^"\\]|\\.)*"', part):
            out.append(go_string(part))
        elif part in texts:
            out.append(texts[part])
        elif m := re.fullmatch(r"strconv\.Quote\((\w+)\)", part):
            out.append('"<%s>"' % m.group(1))
        elif m := re.fullmatch(r"(?:strconv\.\w+|FormatDuration)\((\w+)\)", part):
            out.append("<%s>" % m.group(1))
        elif m := re.fullmatch(r"(\w+)\.(?:String|Error)\(\)", part):
            out.append("<%s>" % m.group(1))
        elif re.fullmatch(r"\w+", part):
            out.append("<%s>" % part)
        else:
            return None
    return "".join(out)


def parse_messages(text, kinds_text):
    """Every lokierr message: id, const, kind, status, shape, constructors, templates, summary."""
    kind_names = dict(re.findall(r'^\s*(Kind\w+):\s*"(\w+)",', kinds_text, re.M))
    texts = {name: go_string(lit) for name, lit in re.findall(r'^\s*(text\w+)\s*=\s*("(?:[^"\\]|\\.)*")', text, re.M)}
    summaries = {}
    for m in re.finditer(r'((?:^\s*//.*\n)+)\s*(Msg\w+)\n', text, re.M):
        summaries[m.group(2)] = " ".join(re.sub(r"^\s*//\s?", "", line).strip() for line in m.group(1).strip().split("\n"))
    # The summary comment starts with the const name and a colon.
    summaries = {k: re.sub(rf"^{k}:\s*", "", v) for k, v in summaries.items()}
    messages = {}
    row = re.compile(r'^\s*(Msg\w+):\s*\{"([a-z-]+)", (Kind\w+), (?:http\.(Status\w+)|(StatusClientClosedRequest)), (Shape\w+)\},', re.M)
    for m in row.finditer(text):
        const, ident, kind, http_status, custom, shape = m.groups()
        messages[const] = {"id": ident, "const": const, "kind": kind_names[kind], "status": None,
                           "http_status": http_status, "shape": SHAPE_NAMES[shape], "constructors": [], "templates": [],
                           "summary": summaries.get(const, "")}
        if custom:
            messages[const]["status"] = STATUS_CONST[custom]
        else:
            messages[const]["status"] = sync_errors.STATUS_NAMES["http." + http_status]
        del messages[const]["http_status"]
    funcs = [(m.start(), m.group(1)) for m in re.finditer(r"^func (\w+)\(", text, re.M)]
    for m in re.finditer(r"newError\((Msg\w+),", text):
        const = m.group(1)
        if const not in messages:
            continue
        # The call's arguments, from the opening parenthesis.
        start = text.index("(", m.start()) + 1
        args, _ = sync_errors.call_arguments(text, start)
        name = [n for pos, n in funcs if pos < m.start()][-1]
        if name not in messages[const]["constructors"]:
            messages[const]["constructors"].append(name)
        template = template_of(args[1], texts) if len(args) > 1 else None
        if template is not None and template not in messages[const]["templates"]:
            messages[const]["templates"].append(template)
    return messages


def route_of(row):
    route = row["route"]
    if route.startswith("/"):
        return "unknown_path" if row["trigger"].startswith("shape:unknown-path") else "other_routes"
    return route


def kind_of(row, spec, limit_msgs):
    if row.get("msg") in limit_msgs:
        return spec["limit_message_kind"]
    trigger = row["trigger"]
    for rule in spec["trigger_kinds"]:
        if "exact" in rule and trigger in rule["exact"]:
            return rule["kind"]
        if "prefix" in rule and trigger.startswith(rule["prefix"]):
            return rule["kind"]
    raise SystemExit(f"error_registry: row {row['id']} (trigger {trigger!r}) matches no rule of trigger_kinds in {SPEC}")


def unmapped_id(row, spec):
    """The Loki message of a recorded error no lokierr constructor renders yet, by the spec's rules; None for a success."""
    status, body = row["loki"]["status"], row["loki"]["body"]
    if status < 300:
        return None
    for rule in spec["unmapped_messages"]:
        if rule["status"] == status and re.search(rule["body"], body):
            return rule["id"]
    raise SystemExit(f"error_registry: row {row['id']} (status {status}, body {body[:60]!r}) has no msg and matches no entry of "
                     f"unmapped_messages in {SPEC}")


def gate_cells(spec):
    """Backend failure and cancel/deadline cells: (matrix route, kind) -> {modes: {mode: gate route names}}."""
    text = read_text(GATE_TEST)
    modes = re.findall(r'^\t"(\w+)",', re.search(r"var errLayerModes = \[\]string\{(.*?)\n\}", text, re.S).group(1), re.M)
    routes = re.findall(r'\{name: "(\w+)", path:', text)
    block = re.search(r"var errLayerModes = \[\]string\{(.*?)\n\}", text, re.S).group(1)
    if len(modes) != len(re.findall(r'"\w+"', block)):
        raise SystemExit(f"error_registry: {GATE_TEST} errLayerModes holds a mode this script cannot read; one quoted mode per line")
    prefixes = sorted(spec["gate_route_map"], key=len, reverse=True)
    mapped = {}
    for name in routes:
        for prefix in prefixes:
            if name.startswith(prefix):
                mapped[name] = spec["gate_route_map"][prefix]
                break
        else:
            raise SystemExit(f"error_registry: error-layer gate route {name!r} matches no gate_route_map entry in {SPEC}")
    for mode in modes:
        if mode not in spec["gate_mode_kinds"]:
            raise SystemExit(f"error_registry: error-layer gate mode {mode!r} is not in gate_mode_kinds of {SPEC}")
    return modes, mapped


def stage_rank(spec, route, stage):
    return spec["route_stage_rank"].get(route, {}).get(stage, spec["stage_rank"][stage])


def check_order(spec, order_rows, messages_by_id):
    """Per message: its stage, who it beats and who beats it in the recorded combinations; problems for any row that
    contradicts the stage ranks."""
    wins, loses, evidence, problems = {}, {}, {}, []
    prefixes = ("instant-metric-", "instant-bad-", "instant-", "labels-", "series-", "stats-", "volume-", "tail-up-", "tail-")
    for row in order_rows:
        tokens = row["trigger"].split(":", 1)[1].split("+")
        stages = []
        for token, ident in zip(tokens, row["issues"]):
            base = token
            for prefix in prefixes:
                if token.startswith(prefix):
                    base = token[len(prefix):]
                    if prefix == "instant-bad-":
                        base = "bad-" + base
                    break
            stages.append(spec["issue_stage"].get(base, spec["message_stage"].get(ident)))
        if None in stages:
            continue  # a message without a stage is reported where the items are built
        winner = row["wins"]
        if winner not in row["issues"]:
            problems.append(f"{row['id']}: the answer {winner!r} is none of the request's errors {row['issues']}")
            continue
        win_rank = min(stage_rank(spec, row["route"], s) for s, i in zip(stages, row["issues"]) if i == winner)
        for stage, ident in zip(stages, row["issues"]):
            if ident == winner and stage_rank(spec, row["route"], stage) == win_rank:
                continue
            if stage_rank(spec, row["route"], stage) < win_rank:
                problems.append(f"{row['id']}: {winner} was answered before {ident}, which the stage ranks of {SPEC} put first")
            if ident != winner:
                wins.setdefault(winner, set()).add(ident)
                loses.setdefault(ident, set()).add(winner)
        evidence.setdefault(winner, []).append(row["id"])
        for ident in row["issues"]:
            if ident != winner:
                evidence.setdefault(ident, []).append(row["id"])
    return wins, loses, evidence, problems


def build():
    spec = load_json(SPEC)
    text = read_text(MESSAGES_GO)
    by_const = parse_messages(text, read_text(KINDS_GO))
    messages = {m["id"]: m for m in by_const.values() if m["id"] != "none"}
    header, rows = load_rows(ANSWERS)
    _, order_rows = load_rows(ORDER)
    known = load_json(KNOWN_DIFFS)
    known_rows = known["rows"]
    limit_msgs = {i for i, m in messages.items() if m["kind"] == "limit"}
    row_ids = {r["id"] for r in rows}
    problems = []

    comparable = [r for r in rows if "not_comparable" not in r]
    for rid in known_rows:
        if rid not in row_ids:
            problems.append(f"{KNOWN_DIFFS}: row {rid} is not a recorded row")
        elif any(r["id"] == rid and "not_comparable" in r for r in rows):
            problems.append(f"{KNOWN_DIFFS}: row {rid} is not comparable, so it cannot differ")
    for r in rows:
        if r.get("msg") and r["msg"] not in messages:
            problems.append(f"{ANSWERS}: row {r['id']} names the unknown message {r['msg']!r}")

    # Classify every row: its route, kind and message item.
    for r in rows:
        r["_route"] = route_of(r)
        r["_kind"] = kind_of(r, spec, limit_msgs)
        r["_item"] = r.get("msg") or None
        if r["_item"] is None:
            u = unmapped_id(r, spec)
            r["_item"] = f"unmapped-{u}" if u else None
        r["_matches"] = r["id"] not in known_rows
        r["_comparable"] = "not_comparable" not in r

    # Representative rows for the end-to-end run: the first comparable row of every route x kind x message.
    e2e_rows, reps = [], {}
    for r in sorted(rows, key=lambda x: x["id"]):
        if not r["_comparable"] or r["loki"]["status"] == 101:
            continue
        key = (r["_route"], r["_kind"], r["_item"] or "-")
        if key not in reps:
            reps[key] = r["id"]
            e2e_rows.append(r["id"])

    # Cells.
    modes, gate_routes = gate_cells(spec)
    leaks = load_json(KNOWN_LEAKS)["leaks"]
    e2e_backend = spec["e2e_backend"]
    cells = {}

    def cell(route, kind):
        return cells.setdefault((route, kind), {"route": route, "kind": kind, "rows": [], "comparable_rows": 0, "matching_rows": 0,
                                                 "known_difference_ids": [], "messages": set(), "e2e_rows": [], "modes": {}})

    for route, kinds in spec["route_kinds"].items():
        for kind in (spec["all_kinds"] if kinds == "all" else kinds):
            cell(route, kind)
    for r in rows:
        c = cell(r["_route"], r["_kind"])
        c["rows"].append(r["id"])
        if r["_item"]:
            c["messages"].add(r["_item"])
        if r["_comparable"]:
            c["comparable_rows"] += 1
            if r["_matches"]:
                c["matching_rows"] += 1
            else:
                c["known_difference_ids"].append(r["id"])
    for rid in e2e_rows:
        r = next(x for x in rows if x["id"] == rid)
        cell(r["_route"], r["_kind"])["e2e_rows"].append(rid)
    leak_ids = {}
    for name, route in gate_routes.items():
        for mode in modes:
            kind = spec["gate_mode_kinds"][mode]
            c = cell(route, kind)
            m = c["modes"].setdefault(mode, {"gate_cells": 0, "leaks": [], "e2e": mode in e2e_backend["cells"].get(route, [])})
            m["gate_cells"] += 1
            for case in leaks.get(f"{name} {mode}", []):
                m["leaks"].append(case)
                leak_ids.setdefault((route, kind), set()).add(case)
    for (route, kind), ids in leak_ids.items():
        cell(route, kind)["known_difference_ids"] += sorted(ids)

    out_cells = []
    for (route, kind), c in sorted(cells.items()):
        backend = bool(c["modes"])
        recorded = c["comparable_rows"] > 0
        mode_info = {m: {"gate_cells": v["gate_cells"], "leaks": sorted(set(v["leaks"])), "e2e": v["e2e"]} for m, v in sorted(c["modes"].items())}
        unit = recorded or backend
        e2e = bool(c["e2e_rows"]) or any(v["e2e"] for v in c["modes"].values())
        reason = ""
        if not recorded and backend:
            reason = spec["backend_cells_reason"]
        elif not recorded and kind == "tenant" and c["rows"]:
            reason = spec["tenant_cells_reason"]
        if recorded and backend:
            matches = c["matching_rows"] == c["comparable_rows"] and not any(v["leaks"] for v in mode_info.values())
        elif recorded:
            matches = c["matching_rows"] == c["comparable_rows"]
        elif backend:
            matches = not any(v["leaks"] for v in mode_info.values())
        else:
            matches = None
        covered = bool(recorded or reason) and unit and e2e and (recorded or backend)
        state = ("match" if matches else "differs") if (recorded or backend) and matches is not None else ("not-comparable" if c["rows"] else "gap")
        out_cells.append({
            "route": route, "kind": kind, "state": state,
            "recorded": recorded, "comparable_rows": c["comparable_rows"], "matching_rows": c["matching_rows"],
            "rows": len(c["rows"]), "proxy_matches": matches, "unit_gate": unit, "e2e": e2e, "covered": covered,
            "known_difference_ids": sorted(set(c["known_difference_ids"])),
            "messages": sorted(c["messages"]), "e2e_rows": c["e2e_rows"], "modes": mode_info,
            "reason": reason,
        })

    # Items.
    wins, loses, evidence, order_problems = check_order(spec, order_rows, messages)
    problems += order_problems
    items = {}
    for ident, m in sorted(messages.items()):
        items[ident] = {"id": ident, "item": f"msg-{ident}", "source": "lokierr", **{k: m[k] for k in ("const", "constructors", "templates", "summary", "kind", "status", "shape")}}
    for rule in spec["unmapped_messages"]:
        items[f"unmapped-{rule['id']}"] = {"id": f"unmapped-{rule['id']}", "item": f"unmapped-{rule['id']}", "source": "recorded", "constructors": [],
                                           "templates": [rule["template"]], "summary": rule["about"], "kind": "unmapped", "status": rule["status"],
                                           "shape": "route", "const": ""}
    for ident, item in items.items():
        mine = [r for r in rows if r["_item"] == ident]
        item["rows"] = sorted(r["id"] for r in mine)
        item["comparable_rows"] = sum(r["_comparable"] for r in mine)
        item["matching_rows"] = sum(r["_comparable"] and r["_matches"] for r in mine)
        item["known_difference_ids"] = sorted(r["id"] for r in mine if r["_comparable"] and not r["_matches"])
        item["routes"] = sorted({r["_route"] for r in mine})
        shapes = set()
        for r in mine:
            body = r["loki"]["body"]
            shapes.add(f"{r['loki']['status']} {r['loki']['content_type'] or 'no Content-Type'}"
                       f"{'; nosniff' if r['loki']['nosniff'] else ''}; {'trailing newline' if body.endswith(chr(10)) else 'no trailing newline' if body else 'no body'}")
        item["body_shapes"] = sorted(shapes)
        item["e2e_rows"] = [rid for rid in e2e_rows if rid in item["rows"]]
        stage = spec["message_stage"].get(ident)
        item["stage"] = stage
        item["wins_over"] = sorted(wins.get(ident, []))
        item["loses_to"] = sorted(loses.get(ident, []))
        item["order_rows"] = sorted(set(evidence.get(ident, [])))
        recorded = bool(mine)
        documented = spec["no_recorded_answer"].get(ident)
        if ident in messages and not recorded and not documented:
            problems.append(f"message {ident} has no recorded Loki answer and no entry in no_recorded_answer of {SPEC}")
        if recorded and documented:
            problems.append(f"message {ident} has recorded rows, so it must not be listed in no_recorded_answer of {SPEC}")
        if ident in messages and ident not in spec["message_stage"]:
            problems.append(f"message {ident} has no stage in message_stage of {SPEC}")
        item["unit"] = [spec["unit_gate_test"]] if item["comparable_rows"] else (documented or {}).get("tests", [])
        item["e2e"] = [spec["e2e_test"]] if item["e2e_rows"] else []
        item["reason"] = (documented or {}).get("reason", "")
        if item["comparable_rows"]:
            item["state"] = "matches" if not item["known_difference_ids"] else "differs"
        elif recorded:
            item["state"] = "recorded-not-comparable"
        elif documented:
            item["state"] = "documented"
        else:
            item["state"] = "gap"
        if documented and ident in messages:
            for t in documented["tests"]:
                if not re.search(rf"^func {t}\(", read_text(GATE_TEST) + read_text("internal/proxy/error_layer_mixed_test.go")
                                 + read_text("internal/proxy/loki_error_answers_replay_test.go"), re.M):
                    problems.append(f"message {ident}: the test {t} named in no_recorded_answer does not exist")
    for ident in messages:
        if ident not in items:
            problems.append(f"message {ident} has no item")

    # The end-to-end markers must be in the test the spec names.
    e2e_text = read_text("test/e2e-compat/error_layer_like_loki_test.go")
    if not re.search(rf"^func {e2e_backend['test']}\(", e2e_text, re.M):
        problems.append(f"the e2e test {e2e_backend['test']} named in e2e_backend does not exist")
    for marker in e2e_backend["markers"]:
        if f'"{marker}"' not in e2e_text:
            problems.append(f"{e2e_backend['test']} has no subtest {marker!r} (e2e_backend.markers)")
    for needle, path in ((spec["e2e_test"], "test/e2e-compat/error_answers_like_loki_test.go"), (spec["unit_gate_test"], "internal/proxy/loki_error_answers_replay_test.go")):
        if not os.path.exists(path) or not re.search(rf"^func {needle}\(", read_text(path), re.M):
            problems.append(f"the test {needle} named in the spec does not exist in {path}")

    total_cmp, match = len(comparable), sum(1 for r in comparable if r["_matches"])
    covered = sum(c["covered"] for c in out_cells)
    summary = {
        "recorded_rows": len(rows), "comparable_rows": total_cmp, "matching_rows": match, "differing_rows": total_cmp - match,
        "not_comparable_rows": len(rows) - total_cmp,
        "match_ratio": round(match / total_cmp, 4) if total_cmp else 0.0,
        "cells": len(out_cells), "covered_cells": covered, "coverage_ratio": round(covered / len(out_cells), 4) if out_cells else 0.0,
        "cells_matching": sum(1 for c in out_cells if c["proxy_matches"]),
        "cells_recorded": sum(1 for c in out_cells if c["recorded"]),
        "cells_e2e": sum(1 for c in out_cells if c["e2e"]),
        "messages": len(messages), "messages_recorded": sum(1 for i in messages if items[i]["rows"]),
        "messages_documented": sum(1 for i in messages if items[i]["state"] == "documented"),
        "unmapped_items": sum(1 for i in items if i.startswith("unmapped-")),
        "e2e_rows": len(e2e_rows), "check_order_rows": len(order_rows),
        "recorded_loki": (re.search(r"Loki (\d+\.\d+\.\d+) answers recorded", header) or [0, ""])[1],
        "recorded_on": (re.search(r"recorded over HTTP on (\d{4}-\d{2}-\d{2})", header) or [0, ""])[1],
    }
    doc = {"description": "Generated by conformance/scripts/error_registry.py. Do not edit. The error compatibility matrix: every route x error kind with whether Loki's answer is recorded, whether the proxy matches it, the unit gate and the end-to-end comparison that cover it, and the known differences; the items for every Loki error message; the scores.",
           "summary": summary, "kinds": spec["kinds"], "cells": out_cells,
           "messages": {i: {k: v for k, v in item.items() if k in ("item", "source", "kind", "status", "state", "rows", "comparable_rows", "matching_rows", "routes", "e2e_rows", "stage")}
                        for i, item in items.items()},
           "e2e_rows": e2e_rows, "known_differences": {"rows": len(known_rows), "ceiling": known.get("ceiling")}}
    return spec, items, doc, problems, messages, rows, out_cells


def yaml_value(value, indent=0):
    """A YAML scalar, or a flow sequence wrapped to 110 columns and indented under its key."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    if value is None:
        return "null"
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, list):
        if not value:
            return "[]"
        pad = " " * (indent + 2)
        lines, current = [], "["
        for n, v in enumerate(value):
            token = json.dumps(v, ensure_ascii=False) + ("," if n < len(value) - 1 else "]")
            if len(current) + len(token) + 1 + indent > 108 and current.strip("["):
                lines.append(current.rstrip())
                current = pad
            current += (" " if current.strip() and not current.endswith("[") and current != pad else "") + token
        lines.append(current)
        return "\n".join(lines)
    raise TypeError(value)


def item_yaml(item, spec, by_ident):
    cov = "recorded-not-comparable" if item["state"] == "recorded-not-comparable" else item["state"]
    lines = [HEADER.rstrip("\n"), f"id: {item['item']}", f"message: {item['id']}", f"source: {item['source']}"]
    if item["source"] == "lokierr":
        lines += [f"const: {item['const']}", f"constructors: {yaml_value(item['constructors'])}"]
    lines += [f"summary: {yaml_value(item['summary'])}", "templates:"]
    lines += [f"  - {yaml_value(t)}" for t in item["templates"]] or ["  []"]
    lines += [f"kind: {item['kind']}", f"status: {item['status']}"]
    lines += [f"error_type: {sync_errors.error_type(item['status']) or 'null'}", f"shape: {item['shape']}",
              f"routes: {yaml_value(item['routes'])}", f"body_shapes: {yaml_value(item['body_shapes'])}"]
    stage = item["stage"]
    if stage:
        lines += ["check_order:", f"  stage: {stage}", f"  rank: {spec['stage_rank'][stage]}",
                  f"  wins_over: {yaml_value(item['wins_over'])}", f"  loses_to: {yaml_value(item['loses_to'])}",
                  f"  rows: {yaml_value(item['order_rows'], 2)}"]
    lines += ["recorded:", f"  rows: {len(item['rows'])}", f"  comparable_rows: {item['comparable_rows']}",
              f"  matching_rows: {item['matching_rows']}", f"  row_ids: {yaml_value(item['rows'], 2)}",
              f"  known_difference_ids: {yaml_value(item['known_difference_ids'], 2)}", f"  e2e_rows: {yaml_value(item['e2e_rows'], 2)}",
              "coverage:", f"  state: {cov}", f"  unit: {yaml_value(item['unit'])}", f"  e2e: {yaml_value(item['e2e'])}"]
    if item["reason"]:
        lines.append(f"  reason: {yaml_value(item['reason'])}")
    return "\n".join(lines) + "\n"


STATUS_HEAD_END = "\nloki_behaviour:"


def status_heads(items, rows):
    """The generated head of each per-status item (everything above loki_behaviour), by file name."""
    errors = load_json(ERRORS_JSON)["summary"]["by_status"]
    heads = {}
    for name in sorted(os.listdir(ITEMS)):
        if not (name.startswith("status-") and name.endswith(".yaml")):
            continue
        key = name[len("status-"):-len(".yaml")]
        info = errors.get(key, {})
        status = int(key) if key.isdigit() else None
        mine = [i for i in items.values() if i["status"] == status]
        row_ids = {rid for i in mine for rid in i["rows"]}
        cmp_rows = [r for r in rows if r["id"] in row_ids and "not_comparable" not in r]
        match = [r for r in cmp_rows if r["_matches"]]
        messages = "\n".join(f"    - {json.dumps(m)}" for m in info.get("messages", [])[:40])
        head = (f"id: status-{key}\nstatus: {key}\nerror_type: {sync_errors.error_type(status) or 'null'}\n"
                "generated:   # rewritten by conformance/scripts/error_registry.py\n"
                f"  proxy_call_sites: {info.get('count', 0)}\n  dynamic_sites: {info.get('dynamic_sites', 0)}\n"
                f"  literal_messages:{chr(10) + messages if messages else ' []'}\n"
                f"  loki_messages: {yaml_value(sorted(i['item'] for i in mine))}\n"
                f"  recorded_rows: {len(row_ids)}\n  comparable_rows: {len(cmp_rows)}\n  matching_rows: {len(match)}\n")
        heads[name] = head
    return heads


def pct(ratio):
    return f"{ratio * 100:.1f}%"


