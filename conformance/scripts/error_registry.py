#!/usr/bin/env python3
"""Error compatibility registry: one item per Loki error message, a route x error kind matrix, and the scores.

Errors and status codes are held to the same standard as answers: every message Loki can answer a client with is a
registry item, every route x error kind is a cell of a coverage matrix, and both are checked against recorded answers
of a real Loki, by the proxy's unit replay and by the end-to-end run on the stack.

Reads (sources of truth, never edited here):
  internal/lokierr/messages.go                      the typed messages (id, kind, status, shape, constructors, text)
  internal/lokierr/testdata/loki_error_answers.jsonl      Loki's recorded answers (internal/testutil/lokirecorded reads it)
  internal/lokierr/testdata/loki_check_order.jsonl         pairs of errors in one request: which one Loki answers
  conformance/registry/error-layer-known-differences.json  the rows the proxy still answers differently (a ratchet,
                                                           held equal to the real replay by TestLokiErrorAnswersReplay)
  conformance/registry/error-layer-known-leaks.json        the backend-failure cells that still leak
  internal/proxy/error_layer_gate_test.go                  the backend failure routes and modes
  conformance/registry/error-coverage-spec.json            the hand-written classification (the one input to edit)
  conformance/registry/generated/proxy/errors.json         the proxy's error call sites (sync_errors.py)

Writes (generated; do not edit):
  conformance/registry/loki/errors/msg-<id>.yaml           one item per lokierr message
  conformance/registry/loki/errors/unmapped-<id>.yaml      one item per Loki message no constructor renders yet
  conformance/registry/loki/errors/status-*.yaml           the generated head of each per-status item
  conformance/registry/generated/error-coverage.json       the matrix, the items' state, the scores, the e2e rows
  docs/error-compatibility-coverage.md                     the published page

Usage:
  error_registry.py                 write everything
  error_registry.py --check [--base-text FILE]
                                    fail when a generated file is stale, a lokierr message has no item, an item has no
                                    recorded answer and no documented reason, or (with the base file) a cell regressed
"""
