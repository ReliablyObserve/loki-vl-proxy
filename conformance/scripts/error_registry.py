def outputs():
    spec, items, doc, problems, messages, rows, cells = build()
    files = {}
    for ident, item in items.items():
        files[f"{ITEMS}/{item['item']}.yaml"] = item_yaml(item, spec, items)
    heads = status_heads(items, rows)
    for name, head in heads.items():
        path = f"{ITEMS}/{name}"
        current = read_text(path)
        tail = current[current.index(STATUS_HEAD_END) + 1:] if STATUS_HEAD_END in current else ""
        files[path] = head + "\n" + tail if tail else head
    files[OUT_JSON] = json.dumps(doc, indent=2, sort_keys=True) + "\n"
    files[OUT_DOC] = render_doc(spec, items, doc, messages)
    return files, items, doc, problems, spec


def status_problems(spec):
    problems = []
    for name in sorted(os.listdir(ITEMS)):
        if name.startswith("status-") and "TODO" in read_text(f"{ITEMS}/{name}"):
            problems.append(f"{ITEMS}/{name} still holds TODO text: write what Loki answers for this status")
    return problems


def regressions(base_text, doc):
    """Cells that lost a check against the base file, and the scores: a message for each."""
    base = json.loads(base_text)
    now = {(c["route"], c["kind"]): c for c in doc["cells"]}
    out = []
    for c in base["cells"]:
        key = (c["route"], c["kind"])
        cur = now.get(key)
        if cur is None:
            out.append(f"cell {key[0]} x {key[1]} is gone")
            continue
        for flag in ("recorded", "proxy_matches", "unit_gate", "e2e", "covered"):
            if c.get(flag) and not cur.get(flag):
                out.append(f"cell {key[0]} x {key[1]} lost {flag}")
    for name in ("match_ratio", "coverage_ratio"):
        if doc["summary"][name] + 1e-9 < base["summary"][name]:
            out.append(f"{name} fell from {base['summary'][name]:.4f} to {doc['summary'][name]:.4f} (a re-recording that added rows can do this; "
                       "then accept the new baseline in conformance/registry/baseline.json with ratchet.py --accept)")
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--base-text", help="the base branch's error-coverage.json, to fail on a cell that lost a check")
    args = parser.parse_args()
    files, items, doc, problems, spec = outputs()
    problems += status_problems(spec)
    if args.check:
        for path, text in files.items():
            if not os.path.exists(path) or read_text(path) != text:
                problems.append(f"{path} is stale; run python3 {SCRIPTS_PATH}")
        known = {f"{ITEMS}/{i['item']}.yaml" for i in items.values()}
        for name in sorted(os.listdir(ITEMS)):
            path = f"{ITEMS}/{name}"
            if (name.startswith("msg-") or name.startswith("unmapped-")) and path not in known:
                problems.append(f"{path} is an item of no lokierr message or recorded Loki message; delete it")
        if args.base_text:
            problems += regressions(read_text(args.base_text), doc)
        for p in problems:
            print(f"error registry: {p}")
        if not problems:
            s = doc["summary"]
            print(f"error registry: {s['messages']} messages, {s['cells']} cells ({s['covered_cells']} covered), "
                  f"{s['matching_rows']}/{s['comparable_rows']} recorded answers match Loki")
        return 1 if problems else 0
    if problems:
        for p in problems:
            print(f"error registry: {p}", file=sys.stderr)
        return 1
    for path, text in files.items():
        os.makedirs(os.path.dirname(path), exist_ok=True)
        write_text(path, text)
    s = doc["summary"]
    print(f"error registry: {s['messages']} messages, {len(items)} items, {s['cells']} cells ({s['covered_cells']} covered), "
          f"{s['matching_rows']}/{s['comparable_rows']} recorded answers match Loki")
    return 0


SCRIPTS_PATH = "conformance/scripts/error_registry.py"

if __name__ == "__main__":
    sys.exit(main())
