package capability

import (
	"fmt"
	"strings"
)

// RenderGatesDoc renders the reference page of the gate table (docs/reference/capability-gates.md): one row per gate
// with its kind, first release, what reads it, how it is observed and its registry item. The page is generated from
// the table, so a gate cannot be added or changed without it.
func RenderGatesDoc() string {
	var b strings.Builder
	b.WriteString("> Generated by `go run ./cmd/configdoc` from the gate table in `internal/capability/gates.go`. Do not edit by hand.\n\n")
	b.WriteString("# Capability gates\n\n")
	b.WriteString("Every input that turns an optimisation or a behaviour on or off is one gate of one table. The proxy decides each gate from the VictoriaLogs release behind it (the lowest release seen in the last window, so a mixed pool or a rolling upgrade never enables a gate one member lacks), the feature probes it runs against VictoriaLogs (`-backend-feature-probes`), and, as hooks, the Loki compatibility target and the client profile of a request. `GET /admin/capabilities` shows the releases seen, every gate and what decided it; the metrics `loki_vl_proxy_backend_version_info`, `loki_vl_proxy_capability_gate`, `loki_vl_proxy_capability_mismatch_total`, `loki_vl_proxy_capability_epoch` and `loki_vl_proxy_backend_feature_probe_total` carry the same.\n\n")
	b.WriteString("## Kinds\n\n")
	b.WriteString("| Kind | Unknown release | A probe that contradicts the release | Probe |\n|---|---|---|---|\n")
	b.WriteString("| `capability` | off (the v1.49.0 floor), except a gate the floor itself has | the observed behaviour wins; the mismatch is logged once and counted | allowed, one per gate |\n")
	b.WriteString("| `safety` | guarded: the gate is off, so the proxy never sends what needs the fix | the more conservative reading wins | never: a crash or a wrong answer cannot be probed without causing it |\n")
	b.WriteString("| `behaviour` | undecided: nothing is predicted from it, neither assumed present nor absent | the observed behaviour wins | allowed |\n\n")
	b.WriteString("With no release readable, a probe that finds a feature present also bounds the release from below: the capabilities of that release's line and earlier ones are then present too (`implied`), so a backend behind `vmauth` that answers `coalesce` keeps dense pattern windowing and column-indexed field values. Only an explicit refusal turns a probed gate off: a timeout, a 5xx, a 401 or 403, a transport error or an open circuit breaker gives no verdict and keeps the previous one, so an outage never flips a gate or moves the digest. Probes use the proxy's own backend client, auth, TLS and headers, bypass the circuit breaker and the outage join, and are never counted as client requests. Every probe reads one fixed one-second window in the year 2000, long before any retention, so it never scans a stored row.\n\n")
	b.WriteString("## Gates\n\n")
	b.WriteString("| Gate | Kind | From | Probe | Read by | Registry item | Citation |\n|---|---|---|---|---|---|---|\n")
	for _, g := range gates {
		probe := "none"
		if g.Probe != nil {
			probe = fmt.Sprintf("`%s` (proven crash-safe on %s and %s)", g.Probe.Path, g.Probe.CrashSafe[0], g.Probe.CrashSafe[1])
		}
		from := "`" + g.FromString() + "`"
		if g.Default && g.From[1] < 49 {
			from += " (below the floor: on by default)"
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s | `vl/capabilities/%s` | %s |\n", g.Name, g.Kind, from, probe, escapeCell(g.Reads), g.Registry, escapeCell(g.Citation))
	}
	b.WriteString("\n## Digest and epoch\n\n")
	b.WriteString("The set of gates has a digest: a content hash of the effective release, its flavour and every gate's on and decided bits. It is the same on every replica of the same backend, so the cross-replica keys that depend on the gate set (held VictoriaLogs refusals and their peer sync, the request flight keys) carry it and an entry built under another gate set is a miss. The epoch counts the changes of the set in this process and moves only when the digest does.\n\n")
	b.WriteString("## Flags\n\n")
	b.WriteString("| Flag | Default | Meaning |\n|---|---|---|\n")
	b.WriteString("| `-backend-version-reprobe-interval` | `5m` | How often the release is read again and the gates probed; `0` disables the periodic round |\n")
	b.WriteString("| `-backend-feature-probes` | `true` | Run the feature probes; `false` decides the gates from the release alone |\n")
	b.WriteString("| `-backend-version-check-timeout` | `5s` | Timeout of each probe request |\n")
	b.WriteString("| `-debug-vl-calls-header` | `false` | Also adds the `X-Loki-VL-Capabilities` response header: the epoch, the digest and the gates that are on |\n")
	return b.String()
}

// escapeCell makes text safe inside a Markdown table cell that MDX also parses.
func escapeCell(s string) string {
	s = strings.ReplaceAll(s, "|", `\|`)
	s = strings.Join(strings.Fields(s), " ")
	parts := strings.Split(s, "`")
	for i := range parts {
		if i%2 == 1 {
			continue
		}
		parts[i] = strings.NewReplacer("{", "&#123;", "}", "&#125;", "<", "&lt;", ">", "&gt;").Replace(parts[i])
	}
	return strings.Join(parts, "`")
}
