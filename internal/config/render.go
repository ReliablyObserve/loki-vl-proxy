	"  backend-max-concurrent-heavy-queries: \"1\"   # one heavy stats state fits in VictoriaLogs memory\n" +
	"  backend-heavy-query-queue-wait: \"25s\"       # still below Grafana's 30s data source timeout\n" +
	"  backend-max-buffered-response-bytes: \"16777216\"  # 16 MiB per buffered response\n" +
	"  manual-range-metric-row-limit: \"250000\"     # about 25 MiB of proxy-side samples\n" +
	"  max-concurrent: \"16\"\n" +
	"```\n\n"

